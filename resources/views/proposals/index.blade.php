                valid_days: 5,
                plat3_name:'', plat3_features:['','','','','',''],
                plat4_name:'', plat4_features:['','','','','',''],
                extra_notes:'', status:'draft',
            };
            if (window.innerWidth < 768) this.panel = 'detail';
        },

        onRubroChange(rubro) {
            this.form.rubro = rubro;
            const cfg = this.rubrosConfig[rubro];
            if (!cfg) return;
            this.form.plat3_name = cfg.plat3.name;
            this.form.plat4_name = cfg.plat4.name;
            const pad = arr => { const r = [...arr]; while(r.length < 6) r.push(''); return r; };
            this.form.plat3_features = pad(cfg.plat3.features);
            this.form.plat4_features = pad(cfg.plat4.features);
        },

        syncPrice() {
            const half = Math.round(this.form.price / 2 * 100) / 100;
            this.form.price_first  = half;
            this.form.price_second = Math.round((this.form.price - half) * 100) / 100;
        },

        async save() {
            this.saving = true;
            const base   = '{{ route("proposals.store") }}';
            const url    = this.creating ? base : base + '/' + this.selected.id;
            const method = this.creating ? 'POST' : 'PUT';
            const body   = {
                ...this.form,
                plat3_features: this.form.plat3_features.filter(f => f && f.trim()),
                plat4_features: this.form.plat4_features.filter(f => f && f.trim()),
            };
            const res  = await fetch(url, {
                method,
                headers: {'Content-Type':'application/json','X-CSRF-TOKEN':'{{ csrf_token() }}','Accept':'application/json'},
                body: JSON.stringify(body)
            });
            const data = await res.json();
            if (this.creating) {
                this.proposals.unshift(data.proposal);
            } else {
                const idx = this.proposals.findIndex(p => p.id === data.proposal.id);
                if (idx > -1) this.proposals[idx] = {...this.proposals[idx], ...data.proposal};
            }
            this.selected = data.proposal;
            this.form = {
                ...data.proposal,
                plat3_features: data.proposal.plat3_features && data.proposal.plat3_features.length ? [...data.proposal.plat3_features] : ['','','','','',''],
                plat4_features: data.proposal.plat4_features && data.proposal.plat4_features.length ? [...data.proposal.plat4_features] : ['','','','','',''],
            };
            this.creating = false;
            this.saving   = false;
        },

        async del() {
            if (!confirm('¿Eliminar esta propuesta?')) return;
            const base = '{{ route("proposals.store") }}';
            await fetch(base + '/' + this.selected.id, {
                method: 'DELETE',
                headers: {'X-CSRF-TOKEN':'{{ csrf_token() }}','Accept':'application/json'}
            });
            this.proposals = this.proposals.filter(p => p.id !== this.selected.id);
            this.selected  = null;
            this.creating  = false;
        },

        printPreview() {
            const num = this.selected?.number || 'BIXO-PREVIEW';
            const w   = window.open('', '_blank');
            w.document.write(window._proposalGen.buildHtml(this.form, num));
            w.document.close();
            w.focus();
            setTimeout(() => w.print(), 800);
        },

        copyWA() {
            const num = this.selected?.number || 'BIXO-NEW';
            const msg = window._proposalGen.buildWA(this.form, num);
            navigator.clipboard.writeText(msg).then(() => alert('¡Copiado! Pega el mensaje en WhatsApp.'));
        },
    };
}
